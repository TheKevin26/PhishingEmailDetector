"""Load the Zenodo "Phishing Email Curated Datasets", clean, deduplicate and split into train/val/test.

Dataset: Champa, A.I. et al., "Phishing Email Curated Datasets", Zenodo, doi:10.5281/zenodo.8339691 (CC BY 4.0)
Label convention: 1 = phishing/malicious, 0 = legitimate.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from phishguard.config import PROCESSED_DIR, RANDOM_SEED, RAW_DIR, REPORTS_DIR  # noqa: E402
from phishguard.preprocessing import normalize_text  # noqa: E402

SOURCES = ["CEAS_08", "Enron", "Ling", "Nazario", "Nigerian_Fraud", "SpamAssasin"]
# Generated by scripts/generate_modern_emails.py to add modern transactional mail (see that file for rationale)
EXTRA_SOURCES = ["Modern_Synthetic"]


def load_source(name: str) -> pd.DataFrame:
    df = pd.read_csv(RAW_DIR / f"{name}.csv", encoding="utf-8", encoding_errors="replace")
    for col in ("subject", "body", "sender"):
        if col not in df.columns:
            df[col] = ""
    df = df[["subject", "body", "sender", "label"]].copy()
    df["source"] = name
    return df


def main() -> None:
    sources = SOURCES + [s for s in EXTRA_SOURCES if (RAW_DIR / f"{s}.csv").exists()]
    frames = [load_source(s) for s in sources]
    df = pd.concat(frames, ignore_index=True)
    stats = {"raw_rows": len(df)}

    df["subject"] = df["subject"].fillna("").astype(str)
    df["body"] = df["body"].fillna("").astype(str)
    df["sender"] = df["sender"].fillna("").astype(str)
    df["label"] = pd.to_numeric(df["label"], errors="coerce")
    df = df[df["label"].isin([0, 1])].copy()
    df["label"] = df["label"].astype(int)

    # Drop empty / near-empty bodies
    df = df[df["body"].str.strip().str.len() >= 20]
    stats["after_empty_filter"] = len(df)

    # Deduplicate on normalised content; drop texts that appear with conflicting labels
    df["_key"] = (df["subject"].map(normalize_text) + " || " + df["body"].str[:5000].map(normalize_text))
    conflict = df.groupby("_key")["label"].nunique()
    conflict_keys = set(conflict[conflict > 1].index)
    stats["conflicting_label_texts"] = len(conflict_keys)
    df = df[~df["_key"].isin(conflict_keys)]
    df = df.drop_duplicates("_key").drop(columns="_key").reset_index(drop=True)
    stats["after_dedup"] = len(df)

    train, temp = train_test_split(df, test_size=0.2, stratify=df["label"].astype(str) + df["source"],
                                   random_state=RANDOM_SEED)
    val, test = train_test_split(temp, test_size=0.5, stratify=temp["label"].astype(str) + temp["source"],
                                 random_state=RANDOM_SEED)

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    for name, part in (("train", train), ("val", val), ("test", test)):
        part.reset_index(drop=True).to_pickle(PROCESSED_DIR / f"{name}.pkl")
        stats[f"{name}_rows"] = len(part)
        stats[f"{name}_phishing"] = int(part["label"].sum())

    stats["per_source"] = df.groupby(["source", "label"]).size().unstack(fill_value=0).to_dict(orient="index")
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "data_stats.json").write_text(json.dumps(stats, indent=2, default=int))
    print(json.dumps(stats, indent=2, default=int))


if __name__ == "__main__":
    main()
